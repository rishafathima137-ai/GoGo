import type { Hotel } from '../types'
import { destinations } from './destinations'

const img = (id: string, w = 1200) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&q=80`

const coverFor = (destinationId: string) => {
  const d = destinations.find((x) => x.id === destinationId)
  return d?.images[0] ?? ''
}

type HotelSeed = Omit<Hotel, 'image' | 'gallery' | 'destinationId'> & {
  destinationId: string
  galleryImages?: string[]
  coverOffset?: number
}

function makeHotel(seed: HotelSeed): Hotel {
  const { galleryImages = [], coverOffset = 0, ...rest } = seed
  const cover = galleryImages[coverOffset] ?? coverFor(seed.destinationId)
  return {
    ...rest,
    image: cover,
    gallery: galleryImages.length > 0 ? galleryImages : [cover],
  }
}

