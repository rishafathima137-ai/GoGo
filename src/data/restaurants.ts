const img = (id: string, w = 800) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&q=80`

const covers: Record<string, string> = Object.fromEntries(
  destinations.map((d) => [d.id, d.images[1] ?? d.images[0]]),
)

type Seed = Omit<Restaurant, 'image'> & { image?: string }

function makeRestaurant(seed: Seed): Restaurant {
  return {
    ...seed,
    image: seed.image ?? covers[seed.destinationId] ?? '',
  }
}

