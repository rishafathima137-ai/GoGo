/** Simple offline mock translation: exact phrase lookup, then a graceful fallback. */
export function mockTranslate(input: string, toCode: string): string {
  const trimmed = input.trim()
  if (!trimmed) return ''
  const lower = trimmed.toLowerCase()

  const exact = phrases.find((p) => p.english.toLowerCase() === lower)
  if (exact?.translations[toCode]) return exact.translations[toCode]

  const keywordMatch = phrases.find((p) => {
    const first = p.english.toLowerCase().split(' ')[0]
    return first.length > 3 && lower.includes(first)
  })
  if (keywordMatch?.translations[toCode]) {
    return `${keywordMatch.translations[toCode]} \u00b7 ${trimmed}`
  }

  return `[${toCode.toUpperCase()}] ${trimmed}`
}

